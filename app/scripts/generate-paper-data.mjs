import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const publicDir = path.resolve(__dirname, "../public");
const outDir = path.resolve(__dirname, "../src/data");

const sections = [
  { file: "resonance_paper_sec00.md", title: "Abstract" },
  { file: "resonance_paper_sec01.md", title: "1. Introduction" },
  { file: "resonance_paper_sec02.md", title: "2. Related Work" },
  { file: "resonance_paper_sec03.md", title: "3. Methodology" },
  { file: "resonance_paper_sec04.md", title: "4. Experiments & Results" },
  { file: "resonance_paper_sec05.md", title: "5. Discussion" },
  { file: "resonance_paper_sec06.md", title: "6. Conclusion" },
];

let output = `// Auto-generated by scripts/generate-paper-data.mjs\n`;
output += `// Do not edit manually.\n\n`;

for (const sec of sections) {
  const filePath = path.join(publicDir, sec.file);
  if (!fs.existsSync(filePath)) {
    console.warn(`Warning: ${filePath} not found, skipping.`);
    continue;
  }
  const content = fs.readFileSync(filePath, "utf-8");
  output += `export const ${sec.file.replace(/\.md$/, "").replace(/-/g, "_")} = ${JSON.stringify(content)};\n`;
}

output += `\n`;
output += `export const paperSections = [\n`;
for (const sec of sections) {
  const varName = sec.file.replace(/\.md$/, "").replace(/-/g, "_");
  output += `  { file: ${JSON.stringify(sec.file)}, title: ${JSON.stringify(sec.title)}, content: ${varName} },\n`;
}
output += `];\n`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "paper-sections.ts"), output);
console.log("Generated src/data/paper-sections.ts");
